"""Generate every number, table and figure used by summary.tex.

Nothing in the report is typed by hand: summary.tex holds prose plus \\input
and \\includegraphics only, so a figure quoted in a sentence cannot drift from
the data behind it. Re-run this, recompile, and the document is consistent by
construction.

    python3 make_report.py [--data-dir data] [--out-dir .]

Reads the output of analyze.py and recomputes none of its derived quantities,
with the single exception noted at seed_table().
"""

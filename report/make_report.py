def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-dir", default="data")
    ap.add_argument("--out-dir", default=".")
    ap.add_argument("--knowns-dir", default="data_knowns",
                    help="GyrB reference run; skipped if absent")
    args = ap.parse_args()

    data, out = Path(args.data_dir), Path(args.out_dir)
    (out / "figures").mkdir(parents=True, exist_ok=True)
    (out / "tables").mkdir(parents=True, exist_ok=True)

    csv = data / "per_molecule.csv"
    if not csv.exists():
        raise SystemExit(
            f"Missing {csv}. Pull the data first:\n"
            "  cd /storage/users/kikolski/screening-dock/results/panel500_v1\n"
            "  tar czf /tmp/report_data.tgz -C docking analysis/per_molecule.csv \\\n"
            "      redock_control.json summary.json -C ../manifests ligands.json\n"
            f"then extract it into {data}/"
        )

    df = pd.read_csv(csv, index_col=0)
    if "seed" in df:
        df["seed"] = df["seed"].astype(str)
    summary = json.loads((data / "summary.json").read_text())
    redock = json.loads((data / "redock_control.json").read_text())

    recs = [c for c in df.columns if c in summary["per_receptor"]]
    human = next(c for c in recs if HUMAN_KEY in c)
    bact = [c for c in recs if c != human]
    # Which bacterial DHFR dhfr_selectivity actually refers to. analyze.py
    # emits one selectivity_<receptor> column per bacterial DHFR plus the
    # headline copy, so the answer is in the data and needs no config -- and
    # picking it by column order is exactly what would mislabel the headline
    # once a second bacterial DHFR exists.
    dhfr_recs = sorted(c for c in bact if "dhfr" in c)
    bact_dhfr = None
    if "dhfr_selectivity" in df:
        bact_dhfr = next(
            (b for b in dhfr_recs
             if f"selectivity_{b}" in df
             and df[f"selectivity_{b}"].equals(df["dhfr_selectivity"])), None)
    if bact_dhfr is None and len(dhfr_recs) == 1:
        bact_dhfr = dhfr_recs[0]
    if bact_dhfr is None and dhfr_recs:
        raise SystemExit(
            f"cannot tell which of {', '.join(dhfr_recs)} dhfr_selectivity "
            "refers to. Re-run analyze.py so per_molecule.csv carries the "
            "selectivity_<receptor> columns.")
    print(f"  {len(df)} molecules, {len(recs)} receptors, human = {human}")

    m = Macros()
    m.add("nMolecules", len(df))
    m.add("nReceptors", len(recs))
    m.add("nBacterial", len(bact))
    m.add("nDockings", summary.get("n_ligand_states", len(df) * len(recs)))
    m.add("humanTarget", pretty(human))
    m.add("bactDhfr", pretty(bact_dhfr) if bact_dhfr else "--")
    # Listed from the data so adding or dropping a receptor cannot leave the
    # title and the opening sentence disagreeing with the tables.
    m.add("bacterialList", ", ".join(pretty(r) for r in sorted(bact)))
    m.add("leFloor", f"{LE_FLOOR:.2f}")
    m.add("marginMin", f"{MARGIN_MIN}")

    lig = data / "ligands.json"
    if lig.exists():
        lj = json.loads(lig.read_text())
        m.add("nInput", lj.get("n_input", len(df)))
        m.add("nScrubFailed", len(lj.get("failures", [])))
    else:
        m.add("nInput", len(df))
        m.add("nScrubFailed", 0)

    for key, col in [("Dhfr", "dhfr_selectivity"), ("Any", "margin_vs_human")]:
        if col not in df:
            continue
        v = df[col].dropna()
        m.add(f"sel{key}N", int((v > 0).sum()))
        m.add(f"sel{key}Pct", f"{100 * (v > 0).mean():.0f}")
        m.add(f"sel{key}Half", int((v >= MARGIN_MIN).sum()))
        m.add(f"sel{key}One", int((v >= 1.0).sum()))
        m.add(f"sel{key}Median", signed(v.median()))
        m.add(f"sel{key}QLo", signed(v.quantile(.25)))
        m.add(f"sel{key}QHi", signed(v.quantile(.75)))

    # The offset test. The matched and the unmatched bacterial DHFR, compared
    # over the molecules scored at both, plus the shift between them: how much
    # of the human-vs-bacterial gap was resolution and cofactor state rather
    # than the pocket.
    others = [b for b in dhfr_recs if b != bact_dhfr]
    if bact_dhfr and len(others) == 1 and all(
            f"selectivity_{b}" in df for b in (bact_dhfr, *others)):
        ctrl = others[0]
        pair = df[[f"selectivity_{bact_dhfr}", f"selectivity_{ctrl}"]].dropna()
        prim_v, ctrl_v = (pair[f"selectivity_{r}"] for r in (bact_dhfr, ctrl))
        m.add("nDhfrCommon", len(pair))
        m.add("offsetControl", pretty(ctrl))
        m.add("offsetPrimaryMedian", signed(prim_v.median()))
        m.add("offsetControlMedian", signed(ctrl_v.median()))
        m.add("offsetPrimaryN", int((prim_v > 0).sum()))
        m.add("offsetControlN", int((ctrl_v > 0).sum()))
        m.add("offsetShift", signed(prim_v.median() - ctrl_v.median()))
        m.add("offsetPct", f"{100 * abs(prim_v.median() - ctrl_v.median()) / abs(ctrl_v.median()):.0f}")

    le_by_rec = {k: v["le_max"] for k, v in summary["per_receptor"].items()}
    best_rec = max(le_by_rec, key=le_by_rec.get)
    m.add("leBest", num(le_by_rec[best_rec], 3))
    m.add("leBestTarget", pretty(best_rec))
    best_bact = max((r for r in le_by_rec if r != human),
                    key=lambda r: le_by_rec[r])
    m.add("leBestBacterial", num(le_by_rec[best_bact], 3))
    m.add("leBestBacterialTarget", pretty(best_bact))

    corr = {r: df[r].corr(df["heavy_atoms"]) for r in recs}
    m.add("sizeCorrLo", signed(min(corr.values())))
    m.add("sizeCorrHi", signed(max(corr.values())))
    m.add("heavyMedian", f"{df['heavy_atoms'].median():.0f}")
    m.add("heavyMin", f"{df['heavy_atoms'].min():.0f}")
    m.add("heavyMax", f"{df['heavy_atoms'].max():.0f}")

    m.add("nRedockPass",
          sum(r.get("best_pose_rank") == 1 for r in redock))
    m.add("nRedockGate", sum(gate_pass(r) for r in redock))
    m.add("nRedockTotal", len(redock))
    m.add("redockThreshold",
          f"{redock[0].get('threshold', 2.0):.1f}" if redock else "2.0")

    selectivity_table(df, bact_dhfr, out / "tables" / "selectivity.tex")
    receptor_table(summary, redock, out / "tables" / "receptors.tex")
    seed_table(df, m, out / "tables" / "seeds.tex")
    near = nearmiss_table(df, out / "tables" / "nearmiss.tex")
    m.add("nNearMiss", len(near))
    if not near.empty:
        # The widest margin and the best efficiency are different molecules;
        # quote both rather than letting one stand in for "the best hit".
        byle = near.sort_values("le_at_best_bacterial", ascending=False).iloc[0]
        m.add("bestLECandidate", rf"\texttt{{{short_id(str(byle.name))}}}")
        m.add("bestLECandidateLE", num(byle["le_at_best_bacterial"]))
        m.add("bestLECandidateScore", num(byle["best_bacterial"]))
        m.add("bestLECandidateMargin", signed(byle["margin_vs_human"]))
        m.add("bestLECandidateTarget", pretty(byle["best_bacterial_target"]))
        m.add("bestLECandidateHeavy", int(byle["heavy_atoms"]))
        m.add("nearMissTargets", ", ".join(
            sorted({pretty(t) for t in near["best_bacterial_target"]})))
    print(f"  tables/          4 files, {len(near)} near-misses")

    style()
    if bact_dhfr:
        fig_selectivity(df, bact_dhfr, out / "figures" / "selectivity.pdf",
                        control=others[0] if len(others) == 1 else None)
    fig_receptors(df, recs, human, out / "figures" / "receptors.pdf")
    fig_efficiency(df, near, out / "figures" / "efficiency.pdf")
    print("  figures/         3 PDFs")

    kn = load_knowns(Path(args.knowns_dir))
    if kn is not None:
        act, best = kn
        krecs = knowns_tables(df, act, best, m, out)
        enrichment(df, act, best, krecs, m)
        fig_knowns(df, best, krecs, out / "figures" / "knowns.pdf")
        print(f"  knowns           {len(act)} compounds, {len(krecs)} receptors")
    else:
        print(f"  knowns           absent in {args.knowns_dir}, section skipped")

    # Everything summary.tex cites from an optional analysis.
    missing = m.default(
              "offsetControl", "offsetPrimaryMedian", "offsetControlMedian",
              "offsetPrimaryN", "offsetControlN", "offsetShift", "offsetPct",
              "nDhfrCommon", "nKnowns", "nKnownsChemotypes", "nKnownsCensored",
              "nKnownsExact", "knownsPotencyLo", "knownsPotencyHi",
              "knownsPotencyFold", "knownsSpearmanLo", "knownsSpearmanHi",
              "knownsScoreSpan", "knownsReachGyrbSaureus",
              "knownsReachGyrbEcoli", "knownsBeatBestGyrbSaureus",
              "knownsBeatBestGyrbEcoli", "knownsAucLo", "knownsAucHi",
              "knownsAucMatchedLo", "knownsAucNull", "knownsEfLo",
              "knownsEfHi", "knownsHeavyMedian")
    # A document built on partial data must say so on its own first page.
    # Without this the placeholders read as typesetting slips rather than as
    # missing inputs, and the PDF can be circulated without anyone noticing.
    m.add("provisionalnote", "" if not missing else (
        r"\begin{center}\fbox{\parbox{0.92\linewidth}{\small\textbf{"
        r"Provisional build.} " + str(len(missing)) + r" quantities were not "
        r"available from the data supplied and appear as ``--'' below. "
        r"Regenerate once the full run is merged.}}\end{center}"))
    if missing:
        print(f"  PROVISIONAL      {len(missing)} macros unavailable: "
              f"{', '.join(sorted(missing)[:4])}...")

    m.write(out / "numbers.tex")


if __name__ == "__main__":
    main()

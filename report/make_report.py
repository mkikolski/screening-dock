def write_table(path: Path, colspec: str, header: list[str],
                rows: list[str]) -> None:
    """Write a complete tabular for \input.

    The whole environment is generated, not just the rows, for two reasons.
    booktabs' \bottomrule expands to \noalign, which TeX requires to be the
    first token after a row separator -- and LaTeX's \input (unlike TeX's
    primitive) emits bookkeeping tokens, so a \bottomrule sitting in the
    document after \input{rows} is always "misplaced". Keeping it in the same
    file preserves the adjacency. It also means the column spec and the header
    are written next to the row builder, so they cannot drift out of step,
    which is its own class of silent breakage.
    """
    body = [rf"\begin{{tabular}}{{{colspec}}}", r"\toprule",
            " & ".join(header) + r" \\", r"\midrule", *rows,
            r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def selectivity_table(df: pd.DataFrame, bact_dhfr: str | None, out: Path) -> None:
    rows = []
    specs = [("margin_vs_human", "best of any bacterial target",
              "different folds")]
    if bact_dhfr and "dhfr_selectivity" in df:
        specs.insert(0, ("dhfr_selectivity", pretty(bact_dhfr),
                         "same fold and cofactor"))
    for col, label, note in specs:
        v = df[col].dropna()
        # Six fields, matching the tabular in summary.tex. The upper quartile
        # is quoted in the prose instead, to keep this table readable.
        rows.append(
            f"{label} & {(v > 0).sum()} / {len(v)} & "
            f"{(v >= MARGIN_MIN).sum()} & {(v >= 1.0).sum()} & "
            f"{signed(v.median())} & {note} \\\\"
        )
    write_table(out, "lccccl",
                ["comparison", "favours bacterial",
                 rf"$\geq{MARGIN_MIN}$", r"$\geq1.0$", "median", "basis"],
                rows)


def gate_pass(r: dict) -> bool:
    """Does this receptor clear the redocking gate?

    Derived from rmsd_best, not read from the record's own `verdict` field:
    that field was written by the pipeline under the original top-pose rule,
    which the project replaced with best-of-nine. Trusting it would print FAIL
    for FabI and GyrB E. coli while the prose says all five pass.
    """
    best = r.get("rmsd_best")
    return best is not None and best <= r.get("threshold", 2.0)


def receptor_table(summary: dict, redock: list[dict], out: Path) -> None:
    by_name = {r["receptor"]: r for r in redock}
    rows = []
    for name, s in sorted(summary["per_receptor"].items()):
        r = by_name.get(name, {})
        top, best, rank = (r.get("rmsd_reported"), r.get("rmsd_best"),
                           r.get("best_pose_rank"))
        rows.append(
            f"{pretty(name)} & {PDB_ID.get(name, '--')} & "
            f"{num(s['score_min'])} & {num(s['score_median'])} & "
            f"{num(s['le_max'], 3)} & "
            f"{'--' if top is None else num(top)} & "
            f"{'--' if best is None else num(best)} & "
            f"{'--' if rank is None else rank} & "
            f"{'pass' if gate_pass(r) else r'\\textbf{FAIL}'} \\\\"
        )
    write_table(out, "llccccccl",
                ["receptor", "PDB", "best", "median", "max LE",
                 "top RMSD", "best RMSD", "rank", "gate"], rows)


def seed_table(df: pd.DataFrame, macros: Macros, out: Path) -> None:
    """Per-seed margins, plus a permutation test on the widest median gap.

    The p-value is the one quantity analyze.py prints but does not save, so it
    is recomputed here by the same method and generator seed
    (default_rng(0), 10k shuffles) to stay identical to the reported figure.
    Both sides count ties toward the null with a tolerance, which is what makes
    them agree: without it the two differ in the third decimal.
    """
    if "seed" not in df:
        write_table(out, "l", ["seed"], [])
        return

    rows = []
    for sd, g in df.groupby("seed"):
        mg = g["margin_vs_human"].dropna()
        le = g["le_at_best_bacterial"].dropna()
        rows.append(
            f"{sd} & {len(g)} & {signed(mg.median())} & "
            f"{signed(mg.quantile(.25))} -- {signed(mg.quantile(.75))} & "
            f"{(mg > 0).sum()} & {num(le.median())} & {num(le.max())} \\\\"
        )
    write_table(out, "lcccccc",
                ["seed", "$n$", "median margin", "interquartile range",
                 "$>0$", "median LE", "max LE"], rows)

    meds = df.groupby("seed")["margin_vs_human"].median().sort_values()
    if len(meds) < 2:
        return
    hi, lo = meds.index[-1], meds.index[0]
    a = df.loc[df["seed"] == hi, "margin_vs_human"].dropna().to_numpy()
    b = df.loc[df["seed"] == lo, "margin_vs_human"].dropna().to_numpy()
    obs = float(np.median(a) - np.median(b))
    pool = np.concatenate([a, b])
    rng = np.random.default_rng(0)
    gaps = np.empty(10000)
    for i in range(gaps.size):
        q = rng.permutation(pool)
        gaps[i] = np.median(q[:a.size]) - np.median(q[a.size:])
    # Ties toward the null, with a tolerance; see the note in analyze.py.
    macros.add("seedPval",
               f"{float((np.abs(gaps) >= abs(obs) - 1e-9).mean()):.3f}")
    macros.add("seedGap", signed(obs))
    macros.add("seedHi", hi)
    macros.add("seedLo", lo)
    macros.add("seedShuffles", r"10\,000")
    macros.add("nSeeds", len(meds))


def nearmiss_table(df: pd.DataFrame, out: Path) -> pd.DataFrame:
    near = df[df["margin_vs_human"] >= MARGIN_MIN].sort_values(
        "margin_vs_human", ascending=False)
    rows = [
        f"\\texttt{{{short_id(str(name))}}} & "
        f"{pretty(r['best_bacterial_target'])} & "
        f"{num(r['best_bacterial'])} & {signed(r['margin_vs_human'])} & "
        f"{num(r['le_at_best_bacterial'])} & {int(r['heavy_atoms'])} \\\\"
        for name, r in near.iterrows()
    ]
    write_table(out, "llcccc",
                ["molecule", "target", "score", "margin", "LE",
                 "heavy atoms"], rows)
    return near



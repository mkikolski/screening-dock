BLUE, RED, GREEN, GREY = "#4C72B0", "#C44E52", "#55A868", "#555555"


def style() -> None:
    plt.rcParams.update({
        "figure.dpi": 150, "savefig.bbox": "tight", "font.size": 9,
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.grid": True, "grid.alpha": 0.25, "grid.linewidth": 0.5,
        "axes.axisbelow": True, "legend.frameon": False,
    })


def _spearman(a: list[float], b: list[float]) -> float:
    """Rank correlation without scipy. Ties are averaged."""
    def rank(xs):
        order = np.argsort(np.asarray(xs, float), kind="mergesort")
        r = np.empty(len(xs), float)
        r[order] = np.arange(1, len(xs) + 1, dtype=float)
        return r
    ra, rb = rank(a), rank(b)
    if ra.std() == 0 or rb.std() == 0:
        return float("nan")
    return float(np.corrcoef(ra, rb)[0, 1])


def load_knowns(d: Path) -> tuple[pd.DataFrame, pd.DataFrame] | None:
    """(activities, best score per compound per receptor) or None if absent.

    Separate run, separate directory: the knowns must never enter the panel's
    own distributions, only be compared against them.
    """
    act_p, sc_p = d / "gyrb_actives.csv", d / "scores.csv"
    if not (act_p.exists() and sc_p.exists()):
        return None
    act = pd.read_csv(act_p)
    sc = pd.read_csv(sc_p)
    sc = sc[sc["status"] == "ok"].copy()
    # Strip molscrub's _<state> suffix, as merge_results.base_name does.
    sc["name"] = sc["ligand"].str.replace(r"_\d+$", "", regex=True)
    best = (sc.sort_values("best_score")
              .groupby(["name", "receptor"], as_index=False).first())
    return act, best


def knowns_tables(df: pd.DataFrame, act: pd.DataFrame, best: pd.DataFrame,
                  m: Macros, out: Path) -> list[str]:
    """Panel-versus-knowns summary and the per-compound listing.

    Returns the receptors compared, in the order the tables use.
    """
    recs = [r for r in sorted(best["receptor"].unique()) if r in df.columns]
    rel = (act["standard_relation"] if "standard_relation" in act
           else pd.Series(["="] * len(act), index=act.index))
    exact = act[rel.astype(str).str.strip() == "="]
    # A "<0.05 nM" record is a bound, not a measurement, so it has no rank.
    pot = dict(zip(exact["name"], exact["standard_value_nM"]))

    spear = []
    stats = {}
    for rec in recs:
        p_s = df[rec].dropna()
        k = best.loc[best["receptor"] == rec].set_index("name")["best_score"]
        worst, bestk = k.max(), k.min()
        reach, beat = int((p_s <= worst).sum()), int((p_s < bestk).sum())
        stats[rec] = dict(pmed=p_s.median(), pbest=p_s.min(), n=len(p_s),
                          kmed=k.median(), kbest=bestk, kworst=worst,
                          reach=reach, beat=beat)
        common = [n for n in k.index if n in pot]
        spear.append(_spearman([float(np.log10(pot[n])) for n in common],
                               [float(k[n]) for n in common]))
        # Letters only: a TeX control sequence cannot contain digits, so a
        # PDB id like 3U2D would silently split into \knownsReach + "3U2D".
        key = "".join(w.capitalize() for w in rec.split("_") if w.isalpha())
        m.add(f"knownsReach{key}", f"{100 * reach / len(p_s):.1f}")
        m.add(f"knownsBeatBest{key}", beat)

    # Transposed: two receptors, six quantities. Metrics down the side reads
    # far better than seven columns across the text width.
    label_row = [
        ("this panel, median", lambda s: num(s["pmed"])),
        ("this panel, best", lambda s: num(s["pbest"])),
        ("known inhibitors, median", lambda s: num(s["kmed"])),
        ("known inhibitors, range",
         lambda s: f'{num(s["kbest"])} to {num(s["kworst"])}'),
        ("panel molecules in that range",
         lambda s: f'{s["reach"]} / {s["n"]}'),
        ("panel molecules beating the best known",
         lambda s: f'{s["beat"]} / {s["n"]}'),
    ]
    write_table(out / "tables" / "knowns.tex",
                "l" + "r" * len(recs),
                ["", *(pretty(r) for r in recs)],
                [lab + " & " + " & ".join(fn(stats[r]) for r in recs) + r" \\"
                 for lab, fn in label_row])

    comp = []
    for _, a in act.sort_values("standard_value_nM").iterrows():
        cells = []
        for rec in recs:
            k = best.loc[(best["receptor"] == rec) & (best["name"] == a["name"]),
                         "best_score"]
            cells.append(num(k.iloc[0]) if len(k) else "--")
        comp.append(f"{a['chemotype'].replace('_', ' ')} & "
                    f"\\textit{{{a['target_organism'].split()[0][0]}.\\,"
                    f"{a['target_organism'].split()[-1]}}} & "
                    f"{a['standard_type']} & "
                    f"{'$<$~' if str(a.get('standard_relation', '=')).strip() == '<' else ''}"
                    f"{a['standard_value_nM']:g} & "
                    f"{int(a['heavy_atoms'])} & " + " & ".join(cells) + r" \\")
    write_table(out / "tables" / "knowns_compounds.tex",
                "lllrr" + "r" * len(recs),
                ["chemotype", "organism", "type", "value / nM",
                 "heavy atoms", *(pretty(r) for r in recs)],
                comp)

    m.add("nKnowns", len(act))
    m.add("nKnownsChemotypes", act["chemotype"].nunique())
    m.add("knownsPotencyLo", f"{act['standard_value_nM'].min():g}")
    m.add("knownsPotencyHi", f"{act['standard_value_nM'].max():g}")
    m.add("knownsPotencyFold",
          f"{act['standard_value_nM'].max() / act['standard_value_nM'].min():.0f}")
    m.add("nKnownsCensored", len(act) - len(exact))
    m.add("nKnownsExact", len(exact))
    m.add("knownsSpearmanLo", signed(min(spear)))
    m.add("knownsSpearmanHi", signed(max(spear)))
    m.add("knownsScoreSpan",
          num(max(best.loc[best["receptor"] == r, "best_score"].max()
                  - best.loc[best["receptor"] == r, "best_score"].min()
                  for r in recs)))
    return recs


def enrichment(df: pd.DataFrame, act: pd.DataFrame, best: pd.DataFrame,
               recs: list[str], m: Macros) -> None:
    """Separation of known actives from the panel, and the size null control.

    The panel is treated as presumed-inactive decoys. They are untested, not
    verified decoys, so this is an estimate -- but the null control is the
    part that matters: if heavy-atom count alone separated the two sets, the
    separation would be a property artefact rather than site complementarity.
    """
    def auc(pos, neg) -> float:
        pos, neg = np.asarray(pos, float), np.asarray(neg, float)
        wins = (pos[:, None] < neg[None, :]).sum()
        ties = (pos[:, None] == neg[None, :]).sum()
        return float((wins + 0.5 * ties) / (len(pos) * len(neg)))

    kha = act.set_index("name")["heavy_atoms"].astype(float)
    pha = df["heavy_atoms"].dropna().astype(float)
    # Bigger is "better" for size, hence the sign flip.
    m.add("knownsAucNull", f"{auc(-kha.to_numpy(), -pha.to_numpy()):.3f}")
    m.add("knownsHeavyMedian", f"{kha.median():.0f}")

    aucs, aucs_m, efs = [], [], []
    for rec in recs:
        pan = df[[rec, "heavy_atoms"]].dropna()
        k = best.loc[best["receptor"] == rec].set_index("name")["best_score"]
        aucs.append(auc(k.to_numpy(), pan[rec].to_numpy()))

        # Decoys matched on heavy atoms, ten per known, each used once.
        used: set[int] = set()
        for n in k.index:
            if n not in kha.index:
                continue
            order = (pan["heavy_atoms"] - kha[n]).abs().sort_values().index
            for idx in order:
                if idx not in used:
                    used.add(idx)
                    if len([u for u in used]) % 10 == 0:
                        break
            for idx in order:
                if len(used) >= 10 * len(k):
                    break
                used.add(idx)
        matched = pan.loc[sorted(used), rec].to_numpy()
        aucs_m.append(auc(k.to_numpy(), matched))

        both = np.sort(np.concatenate([k.to_numpy(), pan[rec].to_numpy()]))
        cut = both[max(1, int(0.01 * len(both))) - 1]
        efs.append(float((k <= cut).mean() / 0.01))

    m.add("knownsAucLo", f"{min(aucs):.3f}")
    m.add("knownsAucHi", f"{max(aucs):.3f}")
    m.add("knownsAucMatchedLo", f"{min(aucs_m):.3f}")
    m.add("knownsEfLo", f"{min(efs):.0f}")
    m.add("knownsEfHi", f"{max(efs):.0f}")


def fig_knowns(df: pd.DataFrame, best: pd.DataFrame, recs: list[str],
               out: Path) -> None:
    fig, axes = plt.subplots(1, len(recs), figsize=(5.6, 2.3), sharey=True)
    for ax, rec in zip(np.atleast_1d(axes), recs):
        p = df[rec].dropna()
        k = best.loc[best["receptor"] == rec, "best_score"]
        ax.hist(p, bins=30, color=BLUE, edgecolor="white", linewidth=0.3,
                label="panel")
        for i, v in enumerate(k):
            ax.axvline(v, color=RED, lw=0.9, alpha=0.85,
                       label="known inhibitors" if i == 0 else None)
        ax.set_title(PLAIN.get(rec, rec), fontsize=8)
        ax.set_xlabel(r"Vina score / kcal mol$^{-1}$", fontsize=8)
        ax.tick_params(labelsize=7)
    np.atleast_1d(axes)[0].set_ylabel("molecules", fontsize=8)
    np.atleast_1d(axes)[0].legend(loc="upper right", fontsize=7)
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)


def fig_selectivity(df: pd.DataFrame, bact_dhfr: str, out: Path,
                    control: str | None = None) -> None:
    v = df["dhfr_selectivity"].dropna()
    ctrl_col = f"selectivity_{control}" if control else None
    overlay = bool(ctrl_col and ctrl_col in df)
    fig, ax = plt.subplots(figsize=(5.4, 2.4))

    bins: object = 36
    if overlay:
        # Both bacterial DHFRs on one axis, sharing bins. The argument of the
        # figure is that a structure matched to the human one on resolution and
        # cofactor oxidation state gives the same distribution as a mismatched
        # one, which is only legible if the two histograms are comparable.
        c = df[ctrl_col].dropna()
        bins = np.linspace(min(v.min(), c.min()), max(v.max(), c.max()), 37)
        ax.hist(c, bins=bins, histtype="step", color=GREY, linewidth=1.1,
                label=f"{PLAIN.get(control, control)}   "
                      f"median {c.median():+.2f}")
    ax.hist(v, bins=bins, color=BLUE, edgecolor="white", linewidth=0.4,
            zorder=0,
            label=(f"{PLAIN.get(bact_dhfr, bact_dhfr)}   "
                   f"median {v.median():+.2f}") if overlay else None)
    ax.axvline(0, color=RED, lw=1.4, ls="--", label="no preference")
    if overlay:
        ax.set_ylim(top=ax.get_ylim()[1] * 1.28)   # headroom for the legend
        ax.set_xlabel(r"score(DHFR human) $-$ score(DHFR $E.\ coli$)"
                      r"   /  kcal mol$^{-1}$")
    else:
        ax.axvline(v.median(), color=GREEN, lw=1.4,
                   label=f"median {v.median():+.2f}")
        ax.set_xlabel(f"score(DHFR human) $-$ score({PLAIN.get(bact_dhfr, bact_dhfr)})"
                      r"   /  kcal mol$^{-1}$")
    ax.set_ylabel("molecules")
    ax.annotate(r"favours bacterial $\rightarrow$", xy=(0.99, 0.86),
                xycoords="axes fraction", ha="right", fontsize=8, color=RED)
    ax.legend(loc="upper left", fontsize=8)
    fig.savefig(out)
    plt.close(fig)


def fig_receptors(df: pd.DataFrame, recs: list[str], human: str,
                  out: Path) -> None:
    order = [r for r in recs if r != human] + [human]
    fig, ax = plt.subplots(figsize=(5.4, 2.6))
    bp = ax.boxplot([df[r].dropna().to_numpy() for r in order],
                    widths=0.6, showfliers=False, patch_artist=True,
                    medianprops=dict(color="black", lw=1.2))
    for patch, name in zip(bp["boxes"], order):
        patch.set_facecolor(RED if name == human else BLUE)
        patch.set_alpha(0.75)
        patch.set_linewidth(0.6)
    ax.set_xticks(range(1, len(order) + 1))
    ax.set_xticklabels([PLAIN.get(n, n).replace(" ", "\n", 1) for n in order],
                       fontsize=7.5)
    ax.set_ylabel(r"best Vina score / kcal mol$^{-1}$")
    ax.invert_yaxis()                      # stronger binding upwards
    ax.annotate("stronger", xy=(0.012, 0.9), xycoords="axes fraction",
                fontsize=8, color=GREY)
    fig.savefig(out)
    plt.close(fig)


def fig_efficiency(df: pd.DataFrame, near: pd.DataFrame, out: Path) -> None:
    fig, ax = plt.subplots(figsize=(5.4, 2.6))
    ax.scatter(df["heavy_atoms"], df["le_at_best_bacterial"], s=9,
               color=BLUE, alpha=0.45, linewidths=0, label="all molecules")
    if not near.empty:
        ax.scatter(near["heavy_atoms"], near["le_at_best_bacterial"], s=28,
                   facecolor="none", edgecolor=RED, linewidths=1.0,
                   label=rf"beats DHFR human by $\geq$ {MARGIN_MIN}")
    ax.axhline(LE_FLOOR, color=GREEN, lw=1.3, ls="--",
               label=f"LE = {LE_FLOOR:.2f}")
    ax.set_xlabel("heavy atoms")
    ax.set_ylabel("ligand efficiency at\nbest bacterial target")
    ax.legend(loc="upper right", fontsize=8)
    fig.savefig(out)
    plt.close(fig)


